/**
 * Get Prime interventions for a specific stage and mode
 */
export function getPrimeInterventionForStage(stage, mode = null) {
    const candidates = TRICKSTER_PRIME.filter(t => t.targetStage.includes(stage));
    if (candidates.length === 0) return null;
    return candidates[Math.floor(Math.random() * candidates.length)];
}

/**
 * Get all Prime interventions for a stage
 */
export function getAllPrimeInterventionsForStage(stage) {
    return TRICKSTER_PRIME.filter(t => t.targetStage.includes(stage));
}

/**
 * Get Prime interventions by archetype
 */
export function getPrimeInterventionsByArchetype(archetype) {
    return TRICKSTER_PRIME.filter(t => t.archetype === archetype);
}

/**
 * Get high-intensity Prime interventions (for Stage 8 crises)
 */
export function getHighIntensityPrimeInterventions(stage) {
    return TRICKSTER_PRIME.filter(t => t.targetStage.includes(stage) && t.intensity >= 4);
}
